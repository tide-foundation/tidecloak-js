// Inlines tide_dpop_auth.html and a CSP computed from its inline blocks into
// src/generated/dpopAuthAsset.js. Hashes are never written by hand.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const htmlPath = path.join(root, 'tide_dpop_auth.html');
const outPath = path.join(root, 'src', 'generated', 'dpopAuthAsset.js');

function hashes(html, tag) {
  const re = new RegExp(`<${tag}(?:\\s[^>]*)?>([\\s\\S]*?)</${tag}>`, 'g');
  return [...html.matchAll(re)].map(
    ([, body]) => `'sha256-${crypto.createHash('sha256').update(body, 'utf8').digest('base64')}'`
  );
}

function build() {
  const html = fs.readFileSync(htmlPath, 'utf8');
  const csp =
    "default-src 'self'; " +
    `script-src 'self' ${hashes(html, 'script').join(' ')}; ` +
    `style-src 'self' ${hashes(html, 'style').join(' ')}`;
  return { html, csp };
}

module.exports = { build };

if (require.main === module) {
  const { html, csp } = build();
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(
    outPath,
    '// Generated by scripts/gen-dpop-asset.cjs. Do not edit.\n' +
      `export const DPOP_AUTH_HTML = ${JSON.stringify(html)};\n` +
      `export const DPOP_AUTH_CSP = ${JSON.stringify(csp)};\n`
  );
}
